 INX
CALL_POINT:
 JSR SUB
AFTER_CALL:
 INY
SECOND_CALL:
 JSR SUB
AFTER_OVER:
 DB $00,$02
DONE:
 JMP $7E67
SUB:
 INX
 INX
SUB_RETURN:
 RTS
 ENDMOD
 END
