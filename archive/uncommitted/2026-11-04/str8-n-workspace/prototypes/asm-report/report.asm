; RAM report companion, linked at $6800. Uses paired BASE1 ASM only.
 MODULE ASM_REPORT
 INCLUDE "asm-equ.inc"

 CODE
RP_ENTRY: JMP RP_REPORT
RP_REF_ENTRY: JMP RP_REFERENCE
RP_DEF_ENTRY: JMP RP_DEFINITION
RP_DISPATCH_ENTRY: JMP RP_DISPATCH
RP_LINE_ENTRY: JMP RP_LINE_NUMBER
RP_PAD_ENTRY: JMP RP_ROW_PAD
RP_DISPATCH:
 PHX
 LDX #<RP_WORD
 LDY #>RP_WORD
 JSR MATCH_TOKEN
 PLX
 BCS RP_SELECTED
 RTS
RP_SELECTED:
 JSR END_LINE
 LDA ERROR
 BNE RP_RETURN
 JSR RP_REPORT
RP_RETURN:
 PLA
 PLA
 PLA
 PLA
 JMP SHELL
RP_REPORT:
 STZ RP_MODE
 JSR REQUIRE_RESULT
 BCC RP_START
 RTS
RP_START:
 LDX #<RP_TITLE
 LDY #>RP_TITLE
 JSR PRINT
 LDA #1
 STA DX_LIST
 JSR ASM_ASSEMBLE
 STZ DX_LIST
 BCC RP_SYMBOLS
 JMP RP_FAILED
RP_SYMBOLS:
 LDX #<RP_SYM_TITLE
 LDY #>RP_SYM_TITLE
 JSR PRINT
 STZ DX_FILTER
 JSR DX_SYMBOL_OUTPUT
 LDA ERROR
 BNE RP_FAILED
 LDX #<RP_XREF_TITLE
 LDY #>RP_XREF_TITLE
 JSR PRINT
 STZ RP_TARGET
RP_NEXT:
 ; Resolve target from deterministic symbol-table order after each assembly.
 LDA #<SYMBOL_START
 STA SYMPTR
 LDA #>SYMBOL_START
 STA SYMPTR+1
 LDX RP_TARGET
 BEQ RP_AT_TARGET
RP_ADVANCE:
 CLC
 LDA SYMPTR
 ADC #20
 STA SYMPTR
 BCC RP_ADVANCE_OK
 INC SYMPTR+1
RP_ADVANCE_OK:
 DEX
 BNE RP_ADVANCE
RP_AT_TARGET:
 LDA SYMPTR+1
 CMP SYMTOP+1
 BNE RP_NAME
 LDA SYMPTR
 CMP SYMTOP
 BNE RP_NAME
 JMP RP_COMPLETE
RP_NAME:
 ; Print the same qualified name as SYMS (local parent included).
 LDY #18
 LDA (SYMPTR),Y
 BPL RP_SHORT_NAME
 LDA #<SYMBOL_START
 STA TABLEPTR
 LDA #>SYMBOL_START
 STA TABLEPTR+1
 LDY #19
 LDA (SYMPTR),Y
 TAX
 BEQ RP_PARENT
RP_PARENT_ADD:
 CLC
 LDA TABLEPTR
 ADC #20
 STA TABLEPTR
 BCC RP_PARENT_OK
 INC TABLEPTR+1
RP_PARENT_OK:
 DEX
 BNE RP_PARENT_ADD
RP_PARENT:
 LDY #0
RP_PARENT_CHAR:
 LDA (TABLEPTR),Y
 BEQ RP_DOT
 JSR PUTC
 INY
 BRA RP_PARENT_CHAR
RP_DOT:
 LDA #'.'
 JSR PUTC
RP_SHORT_NAME:
 LDY #0
RP_NAME_CHAR:
 LDA (SYMPTR),Y
 BEQ RP_NAME_DONE
 JSR PUTC
 INY
 BRA RP_NAME_CHAR
RP_NAME_DONE:
 STZ RP_COL
 LDA SYMPTR
 STA RP_TARGET_PTR
 LDA SYMPTR+1
 STA RP_TARGET_PTR+1
 LDA #':'
 JSR PUTC
 STZ RP_LAST_REF
 STZ RP_LAST_REF+1
 STZ RP_LAST_DEF
 STZ RP_LAST_DEF+1
 LDA #1
 STA RP_MODE
 JSR ASM_ASSEMBLE
 STZ RP_MODE
 BCS RP_FAILED
 JSR STR8V2_RAM_NEWLINE
 JSR STR8V2_RAM_CHECK_CANCEL
 BCS RP_CANCEL
 INC RP_TARGET
 BNE RP_NEXT
RP_COMPLETE:
 LDX #<RP_SUMMARY
 LDY #>RP_SUMMARY
 JSR PRINT
 LDA RESULT_ORIGIN+1
 JSR STR8V2_RAM_HEX_OUT
 LDA RESULT_ORIGIN
 JSR STR8V2_RAM_HEX_OUT
 LDX #<RP_BYTES
 LDY #>RP_BYTES
 JSR PRINT
 LDA RESULT_LEN
 STA VAL
 LDA RESULT_LEN+1
 STA VAL+1
 JSR DECIMAL_OUT
 JSR STR8V2_RAM_NEWLINE
 RTS
RP_CANCEL:
 LDA #E_CANCEL
 STA ERROR
RP_FAILED:
 STZ RP_MODE
 STZ DX_LIST
 JMP DX_ERROR
RP_REFERENCE:
 JSR FIND_SYMBOL
 PHP
 PHA
 PHX
 PHY
 LDA #'R'
 JSR RP_RECORD
 PLY
 PLX
 PLA
 PLP
 RTS
RP_DEFINITION:
 JSR DEFINE_SYMBOL
 PHP
 PHA
 PHX
 PHY
 LDA #'D'
 JSR RP_RECORD
 PLY
 PLX
 PLA
 PLP
 RTS
RP_RECORD:
 STA RP_KIND
 LDA RP_MODE
 BEQ RP_RECORD_DONE
 LDA PASS
 CMP #2
 BNE RP_RECORD_DONE
 LDA ERROR
 BNE RP_RECORD_DONE
 LDA SYMPTR
 CMP RP_TARGET_PTR
 BNE RP_RECORD_DONE
 LDA SYMPTR+1
 CMP RP_TARGET_PTR+1
 BNE RP_RECORD_DONE
 ; Do not clobber expression VAL or parser registers.
 LDA VAL
 PHA
 LDA VAL+1
 PHA
 LDA NUMBER
 PHA
 LDA NUMBER+1
 PHA
 LDA DIGIT
 PHA
 LDA SAVE
 PHA
 LDX #0
 LDA RP_KIND
 CMP #'R'
 BEQ RP_LAST
 LDX #2
RP_LAST:
 LDA LINENO
 CMP RP_LAST_REF,X
 BNE RP_EMIT
 LDA LINENO+1
 CMP RP_LAST_REF+1,X
 BEQ RP_RECORD_POP
RP_EMIT:
 LDA LINENO
 STA RP_LAST_REF,X
 STA VAL
 LDA LINENO+1
 STA RP_LAST_REF+1,X
 STA VAL+1
 LDA RP_COL
 CMP #8
 BCC RP_SAME_ROW
 STZ RP_COL
 JSR STR8V2_RAM_NEWLINE
 LDA #' '
 JSR PUTC
 JSR PUTC
 JSR PUTC
RP_SAME_ROW:
 INC RP_COL
 LDA #' '
 JSR PUTC
 LDA RP_KIND
 JSR PUTC
 JSR DECIMAL_OUT
RP_RECORD_POP:
 PLA
 STA SAVE
 PLA
 STA DIGIT
 PLA
 STA NUMBER+1
 PLA
 STA NUMBER
 PLA
 STA VAL+1
 PLA
 STA VAL
RP_RECORD_DONE:
 RTS
RP_ROW_PAD:
 LDA DX_FIRST
 BNE RP_PAD_DONE
 LDX #6
RP_PAD_LOOP:
 JSR DX_SPACE
 DEX
 BNE RP_PAD_LOOP
RP_PAD_DONE:
 RTS
RP_LINE_NUMBER:
 LDX #0
RP_DEC_DIGIT:
 STZ DIGIT
RP_DEC_SUB:
 SEC
 LDA VAL
 SBC DECIMAL_POWERS,X
 STA NUMBER
 LDA VAL+1
 SBC DECIMAL_POWERS+1,X
 BCC RP_DEC_PRINT
 STA VAL+1
 LDA NUMBER
 STA VAL
 INC DIGIT
 BRA RP_DEC_SUB
RP_DEC_PRINT:
 LDA DIGIT
 CLC
 ADC #'0'
 JSR PUTC
 INX
 INX
 CPX #10
 BNE RP_DEC_DIGIT
 RTS
RP_WORD: DB "REPORT",0
RP_TITLE: DB $0D,$0A,"STR8-N ASM DEVELOPMENT REPORT",$0D,$0A
 DB "========================================",$0D,$0A
 DB "SOURCE / OBJECT LISTING",$0D,$0A
 DB "LINE  ADDR OBJECT BYTES  SOURCE",$0D,$0A
 DB "----- ---- -----------  -----------------",$0D,$0A,0
RP_SYM_TITLE: DB $0D,$0A,"SYMBOL TABLE (assembly order)",$0D,$0A
 DB "VALUE QUALIFIED NAME",$0D,$0A
 DB "----- ----------------",$0D,$0A,0
RP_XREF_TITLE: DB $0D,$0A,"SYMBOL CROSS REFERENCE",$0D,$0A
 DB "D=definition line; R=expression reference line",$0D,$0A
 DB "Repeated references on one line are combined.",$0D,$0A,0
RP_SUMMARY: DB $0D,$0A,"ASSEMBLY COMPLETE  ORIGIN $",0
RP_BYTES: DB "  OBJECT BYTES ",0
RP_MODE: DB 0
RP_TARGET: DB 0
RP_TARGET_PTR: DW 0
RP_KIND: DB 0
RP_COL: DB 0
RP_LAST_REF: DW 0
RP_LAST_DEF: DW 0
RP_END:
 ENDMOD
 END

