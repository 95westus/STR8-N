"""Read-only resident WDC recognition catalogue; no vendor firmware is included.

Fingerprints describe only F800-FFFF. Matching that resident range does not
identify a whole bank, validate its other programs, or prove it can boot here.
"""
import argparse
import binascii
import hashlib
import json
from pathlib import Path

PROFILES = (
    dict(key='wdcmonv2-65c02-resident', name='WDCMONv2', version='2.00', cpu='65C02',
         cpu_code=2, signature='SXB2', reset=0xf818, first=0xf800, bytes=2048,
         crc16=0xec31, fnv32=0xb3898dcf,
         sha256='1c413d54e6c79702de3135861e6018cb4c96b749582e162a9fb3d6985f45ce7b'),
    dict(key='wdcmonv2-65c816-resident', name='WDCMONv2', version='2.00', cpu='65C816',
         cpu_code=0x16, signature='SXB6', reset=0xf818, first=0xf800, bytes=2048,
         crc16=0x4498, fnv32=0xdd0e2926,
         sha256='88382ec47e32205a0246ac623e1dd62417b5ba1862bb06dc8e7f726d2edd3c3e'),
)


def fnv(data):
    value=0x811c9dc5
    for byte in data:
        value=((value^byte)*0x01000193)&0xffffffff
    return value


def fingerprints(data):
    return dict(crc16=binascii.crc_hqx(data,0xffff), fnv32=fnv(data),
                sha256=hashlib.sha256(data).hexdigest())


def identify(bank, profiles=PROFILES):
    bank=bytes(bank)
    if len(bank)!=32768:raise ValueError('Exactly one 32768-byte bank is required')
    result=dict(mark='U+', name=None, version=None, generation=None,
                whole_bank_recognized=False, bootability_verified=False)
    if bank[-4096:]==b'\xff'*4096:
        return dict(result, mark='..', method='erased F sector')
    reset=int.from_bytes(bank[-4:-2],'little')
    signature=bank[0x780c:0x7810]
    if signature not in (b'SXB2',b'SXB6') or not 0xf800<=reset<0xffe0:
        return dict(result, method='no WDC resident signature/vector evidence')
    result.update(mark='W?', name='possible WDCMON', cpu='65C02' if signature==b'SXB2' else '65C816',
                  reset=f'{reset:04X}', resident_range='F800-FFFF',
                  method='signature and plausible reset vector only')
    resident=bank[-2048:]
    actual=fingerprints(resident)
    for profile in profiles:
        if (profile['signature'].encode()==signature and profile['reset']==reset
                and all(actual[key]==profile[key] for key in ('crc16','fnv32','sha256'))):
            result.update(mark='W+',name=profile['name'],version=profile['version'],cpu=profile['cpu'],
                          profile=profile['key'],method='known resident fingerprint and reset vector',
                          fingerprint_scope='resident monitor only; remaining bank unclassified')
            break
    return result


def assembler_catalog():
    rows=['; Generated by tools/map_catalog.py; hashes/labels only, no vendor code.',
          '; Each 11-byte row: CPU, reset word, CRC16, FNV32, name pointer.',
          'MAP_WDC_CATALOG:']
    for number,p in enumerate(PROFILES,1):
        raw=bytes((p['cpu_code'],))+p['reset'].to_bytes(2,'little')+p['crc16'].to_bytes(2,'little')+p['fnv32'].to_bytes(4,'little')
        rows.append('        DB '+','.join(f'${b:02X}' for b in raw))
        rows.append(f'        DW MAP_WDC_NAME_{number}')
    for number,p in enumerate(PROFILES,1):
        rows.append(f'MAP_WDC_NAME_{number}: DB "{p["name"]} {p["version"]} {p["cpu"]}",0')
    return '\n'.join(rows)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bank-image',type=Path)
    parser.add_argument('--emit-asm',type=Path)
    args=parser.parse_args()
    if args.bank_image:print(json.dumps(identify(args.bank_image.read_bytes()),indent=2))
    if args.emit_asm:args.emit_asm.write_text(assembler_catalog(),encoding='ascii',newline='\n')
    if not args.bank_image and not args.emit_asm:parser.error('Choose --bank-image or --emit-asm')
