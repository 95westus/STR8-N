"""Port the preserved b35 SRAM/WORK algorithms; no build or board access."""
import hashlib,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate(destination=None):
    reference=ROOT/'monitors/reference/sram-work-b35.inc'
    s=reference.read_text()
    # Undo old generated long-branch scaffolding before sizing the new link.
    inverse=dict(BCC='BCS',BCS='BCC',BEQ='BNE',BNE='BEQ',BMI='BPL',BPL='BMI',BVC='BVS',BVS='BVC')
    pattern=r'^([ \t]*)(B(?:CC|CS|EQ|NE|MI|PL|VC|VS))\s+((?:SM|WK)_\w*LONG_\w+)\s*\n[ \t]*JMP\s+(\w+)\s*\n\3:\s*\n'
    s=re.sub(pattern,lambda m:m[1]+inverse[m[2]]+' '+m[4]+'\n',s,flags=re.M)
    s=s.replace("#'SM_C_R'","#'R'").replace("#'WK_P'","#'P'").replace("#'WK_Q'","#'Q'")
    a,b=s.index('SM_C_DISCOVER:'),s.index('; Each manager write')
    s=s[:a]+'''SM_C_DISCOVER:
        LDA #1
        STA SM_C_MANAGED
        STZ SM_D_COUNT
        LDA #0
        JMP SM_C_TRANSFER
'''+s[b:]
    a,b=s.index('WK_DISCOVER:'),s.index('WK_BUF_PTR:')
    s=s[:a]+'''WK_DISCOVER:
        STZ WK_N
        LDA #0
        JMP WK_TRANSFER
'''+s[b:]
    s=s.replace('JSR $66A6','JSR SW_TRANSFER')
    s=s.replace('CMP $7D0B','CMP SW_RAM_LAST+1').replace('CMP $7D0A','CMP SW_RAM_LAST')
    # Caller blocks and I/O buffers may not overlap this RAM-resident library.
    a,b=s.index('        CPX #$65'),s.index('SM_C_API_COPY:')
    s=s[:a]+'''        CPX #$20
        BCS SM_C_API_BAD
        CPX #$1F
        BNE SM_C_API_COPY
        CMP #$E1
        BCS SM_C_API_BAD
'''+s[b:]
    a,b=s.index('WK_CPU_RANGE:'),s.index('WK_PROGRAM_CHECK:')
    s=s[:a]+'''WK_CPU_RANGE:
        LDA WK_C+1
        CMP #2
        BCC WK_BAD_ARG
        CLC
        LDA WK_C
        ADC WK_N
        STA WK_TEMP
        LDA WK_C+1
        ADC #0
        BCS WK_BAD_ARG
        CMP #$20
        BCC WK_CPU_OK
        BNE WK_BAD_ARG
        LDA WK_TEMP
        BNE WK_BAD_ARG
WK_CPU_OK:
        LDA #0
        RTS
'''+s[b:]
    # Mount still accepts legacy records at their original RAM destinations.
    # Only an actual save/restore is restricted to this overlay's user window.
    s=s.replace('        JSR SM_C_ALLOCATE\n', '        JSR SW_COPY_RANGE\n        BNE SM_C_SAVE_RETURN\n        JSR SM_C_ALLOCATE\n',1)
    s=s.replace('SM_C_RESTORE:\n        JSR SM_C_LOAD_RECORD\n',
        'SM_C_RESTORE:\n        JSR SM_C_LOAD_RECORD\n        JSR SW_COPY_RANGE\n        BNE SM_C_SAVE_RETURN\n',1)
    # Legacy G is an explicit RAM jump; no old resident/XIP address survives.
    s=s.replace('JSR B29_APP_CHECK','JSR SW_RUN_CHECK').replace('JMP X28_EXEC','JMP SW_RUN')
    s=s.replace('SM_C_QUIT:   JMP $7E67','SM_C_QUIT:   JMP SW_SUB_Q')
    s=s.replace('        JMP $7E67','        JMP SW_SUB_Q')
    s=s.replace('SM_C_CON_COMMAND:\n',"SM_C_CON_COMMAND:\n        LDA SM_C_LINE\n        CMP #'!'\n        BNE SW_SM_COMMAND\n        JMP SW_CONTROLS\nSW_SM_COMMAND:\n",1)
    s,n=re.subn(r"(?m)^([ \t]*)CMP #'Q'\n[ \t]*BEQ WK_QUIT",
        "        CMP #'!'\n        BNE SW_WK_COMMAND\n        JMP SW_CONTROLS\nSW_WK_COMMAND:\n        CMP #'Q'\n        BEQ WK_QUIT",s,count=1)
    assert n==1
    s=s.replace('SRAM 1.4','SRAM 1.4 / BASE1 PR05 gSW_GENERATION_TEXT').replace('WORK 1.4','WORK 1.4 / BASE1 PR05 gSW_GENERATION_TEXT')
    assert not re.search(r'\$7D0[0-9A-F]|\$66A6|X28_|B29_APP_CHECK',s)
    out=Path(destination) if destination else ROOT/'monitors/native/sram-work-classic.inc'
    out.write_text('; Generated by tools/port_sram_work.py; preserved b35 algorithms.\n'
        +'; Reference SHA256 '+hashlib.sha256(reference.read_bytes()).hexdigest()+'\n'+s,encoding='utf-8',newline='\n')
    print('Ported SRAM delete/reclaim/format and WORK claim/I/O/layout algorithms; no device access.')

if __name__=='__main__':generate()
