"""Adapt the preserved maintenance algorithms; no build, simulator or device."""
import hashlib
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def generate(features=False,destination=None):
    src=ROOT/'monitors/reference/bank-maint-2.4.inc'
    s=src.read_text()
    definitions=s[:s.index('MM_START:')]
    core=s[s.index('MM_BM_MENU:'):s.index('MM_BM_MAP:')]
    # VERSION, TABLE and BOOT are normalized before the original first-letter parser.
    core=core.replace('JSR MM_BN_TRY','JSR MB_ALIASES\n                        JSR MM_BN_TRY',1)
    if not features:core=core.replace('JMP MM_X_COPY','JMP MM_BM_BAD')
    a,b=core.index('MM_VALID_RANGE:'),core.index('MM_CONFIRM:')
    core=core[:a]+'''MM_VALID_RANGE:
        PHA
        LDA MM_LAST
        CMP MM_FIRST
        LDA MM_LAST+1
        SBC MM_FIRST+1
        PLA
        BCC MM_RANGE_FAIL
        CMP #$FF
        BEQ MM_RANGE_RAM
        LDA MM_FIRST+1
        CMP #$80
        RTS
MM_RANGE_RAM:
        LDA MM_FIRST+1
        CMP #2
        BCC MM_RANGE_FAIL
        LDA MM_LAST+1
        CMP #$20
        BCS MM_RANGE_FAIL
MM_RANGE_OK:
        SEC
        RTS
MM_RANGE_FAIL:
        CLC
        RTS
'''+core[b:]
    a,b=core.index('MM_CONFIRM:'),core.index('MM_SET_POINTERS:')
    core=core[:a]+'''MM_CONFIRM:
        LDA MM_DB
        CMP #$FF
        BEQ MB_CONFIRM_PLAN
        CMP #2
        BCS MM_CONFIRM_NO
        CMP #1
        BNE MB_CONFIRM_PLAN
        ; The new MAINT RP occupies B1:8-A. No override here.
        LDA MM_TO+1
        CMP #$B0
        BCC MM_CONFIRM_NO
MB_CONFIRM_PLAN:
        LDX #<MM_PLAN_TEXT
        LDY #>MM_PLAN_TEXT
        JSR MM_PRINT
        LDX #<MM_BM_LINE
        LDY #>MM_BM_LINE
        JSR MM_PRINT
        LDX #<MM_DEST_TEXT
        LDY #>MM_DEST_TEXT
        JSR MM_PRINT
        LDA MM_DB
        JSR MM_SPACE_NAME
        LDA #':'
        JSR MM_PUTC
        LDA MM_TO+1
        JSR MM_HEX
        LDA MM_TO
        JSR MM_HEX
        LDX #<MM_CONFIRM_TEXT
        LDY #>MM_CONFIRM_TEXT
        JSR MM_PRINT
        JSR MM_READLINE
        BCC MM_CONFIRM_NO
        LDA MM_BM_LINE
        CMP #'Y'
        BNE MM_CONFIRM_NO
        LDA MM_BM_LINE+1
        BNE MM_CONFIRM_NO
        SEC
        RTS
MM_CONFIRM_NO:
        CLC
        RTS
'''+core[b:]
    parser=s[s.index('; Parser:'):s.index('; Local RAM flash engine.')]
    strings=s[s.index('MM_TITLE:'):s.index('; X bank NAME S NAME')]
    strings=strings.replace('STR8-N BANK MAINT 2.4','STR8-N BANK MAINT 2.4 / BASE1 PR05 g1')
    strings=strings.replace('X bank NAME S NAME / X S NAME bank NAME',
        'X bank NAME P NAME / X P NAME bank NAME; source retained')
    if not features:strings=re.sub(r'^\s*DB "X bank NAME P NAME / X P NAME bank NAME; source retained".*\n','',strings,flags=re.M)
    strings=strings.replace(' Writes need Y. Reserved source/firmware protected.',
        ' Writes: Y. B1:8-A, B2 and B3 protected.')
    # Keep the reference board-name format and exact-YES/commit-last writer.
    naming=s[s.index('MM_TZ_PTR EQU'):s.index('; BN,1,0;')]+s[s.index('MM_BN_READ:'):s.index('MM_MAP_FIRMWARE:')]
    if features:naming=naming.replace('LDA #$9C','LDA #MB_META_FIRST_PAGE').replace('CMP #$A0','CMP #MB_META_END_PAGE')
    # Share the existing verified, commit-last32-byte programmer with ED/1.
    a,b=naming.index('        LDX #31\nMM_BN_SAVE_ZP:'),naming.index('MM_BN_JOURNAL_MAGIC')
    # The first JOURNAL_MAGIC occurrence is a reference, not its definition.
    b=naming.index('MM_BN_JOURNAL_MAGIC DB')
    tail=naming[a:b]
    cut=tail.index('        JSR MM_BN_READ\n')
    readback=tail[cut:]
    programmer=tail[:cut].replace('JSR X28_C9','JSR MB_META_BYTE')
    programmer=programmer.replace('BNE MM_BN_REFUSE','BNE MB_META_FAILED')
    programmer+='        SEC\n        RTS\nMB_META_FAILED:\n        CLC\n        RTS\n'
    if features:naming=naming[:a]+'        JSR MB_META_PROGRAM\n        BCC MM_BN_REFUSE\n'+readback+'MB_META_PROGRAM:\n'+programmer+naming[b:]
    # MM_BN formats are guarded RAM calls, never legacy E/F absolute addresses.
    local=definitions+core+parser+strings+naming
    inverse={'BCC':'BCS','BCS':'BCC','BEQ':'BNE','BNE':'BEQ','BMI':'BPL','BPL':'BMI','BVC':'BVS','BVS':'BVC'}
    pattern=r'^([ \t]*)(B(?:CC|CS|EQ|NE|MI|PL|VC|VS))\s+(MM_\w*LONG_\w+)\s*\n[ \t]*JMP\s+(\w+)\s*\n\3:\s*\n'
    local=re.sub(pattern,lambda m:m[1]+inverse[m[2]]+' '+m[4]+'\n',local,flags=re.M)
    # An error is returned through the live BATCH state, outside the editor.
    local=local.replace('MM_BM_HELP:','MM_BM_HELP:')
    out=Path(destination) if destination else ROOT/'monitors/native/bank-maint-classic.inc'
    out.write_text('; Generated by tools/port_bank_maint.py from preserved project source.\n'
        +'; Reference SHA256 '+hashlib.sha256(src.read_bytes()).hexdigest()+'\n'+local,encoding='utf-8',newline='\n')
    print('Generated classic maintenance with shared metadata programmer and named-copy dispatch; legacy XIP bindings excluded.')


if __name__=='__main__':generate()
